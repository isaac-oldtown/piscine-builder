"""PROGRESS.md, regenerated from the journal after every check. Never edited
by hand: the journal is the record, this is a view of it."""

from __future__ import annotations

import math
from dataclasses import dataclass, field

from proctor import course, journal, report
from proctor.compat import float_display, io_error, write_text
from proctor.errors import Error
from proctor.render import cell, code_span

# Gaps longer than this between two checks are breaks, not work.
SESSION_GAP = 45 * 60


@dataclass(kw_only=True)
class UnitStats:
    unlocked: int | None = None
    passed: int | None = None
    attempts: int = 0
    attempts_to_pass: int | None = None
    active: int = 0
    fails_by_cat: dict[str, int] = field(default_factory=dict)
    fails_by_item: dict[str, int] = field(default_factory=dict)
    warnings_at_pass: int | None = None


@dataclass(kw_only=True)
class Stats:
    units: dict[str, UnitStats]
    checks: list[journal.Event]
    active_by_day: dict[int, int]
    first: int | None
    last: int | None


def compute(events: list[journal.Event]) -> Stats:
    s = Stats(units={}, checks=[], active_by_day={}, first=None, last=None)
    evs = sorted(events, key=lambda e: e.t)
    prev: int | None = None
    for e in evs:
        if s.first is None:
            s.first = e.t
        s.last = e.t
        u = s.units.get(e.unit)
        if u is None:
            u = s.units[e.unit] = UnitStats()
        match e.ev:
            case "unlock":
                if u.unlocked is None:
                    u.unlocked = e.t
            case "pass":
                if u.passed is None:
                    u.passed = e.t
                    u.attempts_to_pass = max(u.attempts, 1)
            case "check":
                if prev is not None:
                    gap = max(e.t - prev, 0)
                    if gap <= SESSION_GAP:
                        u.active += gap
                        day = journal.day_of(e.t)
                        s.active_by_day[day] = s.active_by_day.get(day, 0) + gap
                u.attempts += 1
                if e.ok is True:
                    if u.passed is None:
                        u.warnings_at_pass = e.warnings
                else:
                    if e.cat is not None:
                        u.fails_by_cat[e.cat] = u.fails_by_cat.get(e.cat, 0) + 1
                    if e.item is not None:
                        u.fails_by_item[e.item] = u.fails_by_item.get(e.item, 0) + 1
                s.checks.append(e)
            case _:
                pass
        prev = e.t
    return s


def pct(a: int, b: int) -> str:
    if b == 0:
        return "n/a"
    return f"{(a * 100 + b // 2) // b}%"


def streak(active_days: set[int], today: int) -> int:
    d = today if today in active_days else today - 1
    n = 0
    while d in active_days:
        n += 1
        d -= 1
    return n


def _fsum(xs: list[float]) -> float:
    """Added in order (Python's `sum` compensates rounding errors), from 0.0
    so that nothing done yet prints `0 h`, not `-0 h`."""
    total = 0.0
    for x in xs:
        total += x
    return total


def render(c: course.CourseDir, events: list[journal.Event]) -> str:
    st = compute(events)
    state = c.state()
    total_units = len(c.units)
    passed = [u.id for u in c.units if u.id in state.passed]
    total_active = sum(u.active for u in st.units.values())
    checks = len(st.checks)
    ok_checks = sum(1 for e in st.checks if e.ok is True)
    passed_stats = [st.units[id] for id in passed if id in st.units]
    first_try = sum(1 for u in passed_stats if u.attempts_to_pass == 1)
    if not passed_stats:
        avg_attempts = "n/a"
    else:
        tries = sum(u.attempts_to_pass for u in passed_stats if u.attempts_to_pass is not None)
        avg_attempts = f"{float(tries) / float(len(passed_stats)):.1f}"
    check_days = {journal.day_of(e.t) for e in st.checks}
    today = journal.day_of(journal.now())
    if st.first is not None and st.last is not None:
        weeks = max(float(max(st.last - st.first, 0)) / (7.0 * 86_400.0), 1.0 / 7.0)
    else:
        weeks = 0.0

    s = f"# Progress: {c.course.title}\n\n"
    s += "Generated by proctor from `.proctor/journal.jsonl` after every check. Do not edit by hand. Times are UTC.\n\n"
    s += "## Dashboard\n\n| Metric | Value |\n|--------|-------|\n"
    n = len(state.skipped)
    skipped = "" if n == 0 else f", {n} stretch goal(s) skipped"
    s += f"| Completion | {len(passed)} / {total_units} units ({pct(len(passed), total_units)}){skipped} |\n"
    current_done = state.current is not None and state.done(state.current)
    if current_done:
        nxt = state.next_locked(c)
        if nxt is not None:
            next_ = f"`{nxt.id}` (run `proctor next` to unlock it)"
        else:
            next_ = "none: the course is complete"
        s += f"| Next | {next_} |\n"
    elif state.current is not None:
        cur = state.current
        cur_stats = st.units.get(cur)
        unlocked = cur_stats.unlocked if cur_stats is not None else None
        since = journal.date(unlocked) if unlocked is not None else ""
        s += f"| Current | `{cur}` (in progress, since {since}) |\n"
    s += f"| Checks run | {checks} ({ok_checks} OK, {checks - ok_checks} KO) |\n"
    s += f"| First-try passes | {first_try} / {len(passed)} ({pct(first_try, len(passed))}) |\n"
    s += f"| Average checks to pass | {avg_attempts} |\n"
    s += f"| Active time (estimate) | {journal.duration(total_active)} |\n"
    s += f"| Active days | {len(check_days)} (current streak: {streak(check_days, today)} day(s)) |\n"
    if st.first is not None:
        s += f"| Started | {journal.date(st.first)} |\n"
    if weeks > 0.0:
        hpw = float(total_active) / 3600.0 / weeks
        t = c.course.hours_per_week
        target = f" (target {float_display(t)} h)" if t is not None else ""
        s += f"| Pace | {float(len(passed)) / weeks:.1f} units / week, {hpw:.1f} h / week{target} |\n"
    sc = schedule(c, events, journal.now())
    if sc is not None:
        s += schedule_md(sc)

    s += "\n## Units\n\n| Unit | Difficulty | Status | Unlocked | Passed | Checks | First try | Active time | Most failed check |\n|------|-----------|--------|----------|--------|--------|-----------|-------------|-------------------|\n"
    for u in c.units:
        if u.id not in state.unlocked:
            continue
        us = st.units.get(u.id)
        if u.id in state.skipped:
            status = "skipped (stretch)"
        elif u.id in state.passed:
            status = "passed"
        else:
            status = "in progress"
        # `max_by_key`: the last of equal maxima, in key order.
        best: tuple[str, int] | None = None
        if us is not None:
            for k, cnt in sorted(us.fails_by_item.items()):
                if best is None or cnt >= best[1]:
                    best = (k, cnt)
        most = "none"
        if best is not None:
            most = f"{cell(code_span(best[0]))} ({best[1]}x)"
        attempts_to_pass = us.attempts_to_pass if us is not None else None
        if attempts_to_pass is None:
            u_first_try = ""
        elif attempts_to_pass == 1:
            u_first_try = "yes"
        else:
            u_first_try = "no"
        difficulty = str(u.difficulty) if u.difficulty is not None else ""
        unlocked_at = (
            journal.date(us.unlocked) if us is not None and us.unlocked is not None else ""
        )
        passed_at = journal.date(us.passed) if us is not None and us.passed is not None else ""
        attempts = us.attempts if us is not None else 0
        active = journal.duration(us.active) if us is not None else ""
        s += f"| `{u.id}` | {difficulty} | {status} | {unlocked_at} | {passed_at} | {attempts} | {u_first_try} | {active} | {most} |\n"

    by_cat: dict[str, int] = {}
    by_item: dict[str, int] = {}
    for us in st.units.values():
        for k, cnt in us.fails_by_cat.items():
            by_cat[k] = by_cat.get(k, 0) + cnt
        for k, cnt in us.fails_by_item.items():
            by_item[k] = by_item.get(k, 0) + cnt
    fails = sum(by_cat.values())
    if fails > 0:
        s += "\n## Where checks fail\n\nWhich step stopped a failing check. A high share points at a habit to work on.\n\n| Step | Failures | Share |\n|------|----------|-------|\n"
        cats = sorted(sorted(by_cat.items()), key=lambda kv: -kv[1])
        for k, cnt in cats:
            s += f"| {k} | {cnt} | {pct(cnt, fails)} |\n"
        items = sorted(sorted(by_item.items()), key=lambda kv: -kv[1])
        s += "\nMost failed checks: {}.\n".format(
            ", ".join(f"{code_span(k)} ({cnt}x)" for k, cnt in items[:5])
        )

    by_diff: dict[int, list[int]] = {}
    for u in c.units:
        us_ = st.units.get(u.id)
        d = u.difficulty
        if d is not None and us_ is not None and us_.attempts_to_pass is not None:
            a = us_.attempts_to_pass
            e = by_diff.setdefault(d, [0, 0, 0])
            e[0] += 1
            e[1] += a
            e[2] += int(a == 1)
    if by_diff:
        s += "\n## By difficulty\n\n| Difficulty | Units passed | Average checks to pass | First-try rate |\n|-----------|--------------|------------------------|----------------|\n"
        for d, (cnt, a, f) in sorted(by_diff.items()):
            s += f"| {d} / 5 | {cnt} | {float(a) / float(cnt):.1f} | {pct(f, cnt)} |\n"

    mastered: set[str] = set()
    learning: set[str] = set()
    for u in c.units:
        if u.id in state.passed:
            mastered.update(u.concepts)
        elif u.id in state.unlocked:
            learning.update(u.concepts)
    learning -= mastered
    if mastered or learning:
        s += "\n## Concepts\n\n"
        if mastered:
            s += f"- Practised: {', '.join(sorted(mastered))}\n"
        if learning:
            s += f"- In progress: {', '.join(sorted(learning))}\n"

    warn: list[tuple[str, int]] = []
    for u in c.units:
        us_ = st.units.get(u.id)
        if us_ is not None and us_.warnings_at_pass is not None:
            warn.append((u.id, us_.warnings_at_pass))
    if any(w > 0 for _, w in warn):
        s += "\n## Build warnings at pass\n\n{}\n".format(
            ", ".join(f"`{uid}`: {w}" for uid, w in warn)
        )

    weeks_map: dict[int, list[int]] = {}
    for e_ in st.checks:
        w_ = weeks_map.setdefault(journal.week_start(e_.t), [0, 0, 0])
        w_[0] += 1
        w_[1] += int(e_.ok is True)
    for day, secs in sorted(st.active_by_day.items()):
        wk = day - (day + 3) % 7
        weeks_map.setdefault(wk, [0, 0, 0])[2] += secs
    if weeks_map:
        s += "\n## Weekly activity\n\n| Week of | Checks | OK | Active time |\n|---------|--------|----|-------------|\n"
        for wk, (cnt, ok, secs) in sorted(weeks_map.items(), reverse=True)[:12]:
            s += f"| {journal.date(wk * 86_400)} | {cnt} | {ok} | {journal.duration(secs)} |\n"

    if st.checks:
        s += "\n## Recent checks\n\n| When | Unit | Result | Seed |\n|------|------|--------|------|\n"
        for e_ in list(reversed(st.checks))[:10]:
            if e_.ok is True:
                p_ = e_.passed if e_.passed is not None else 0
                t_ = e_.total if e_.total is not None else 0
                result = f"OK {p_}/{t_}"
            else:
                what = e_.item if e_.item is not None else ""
                cat = e_.cat if e_.cat is not None else ""
                result = f"KO {cat}: {code_span(report.truncate(what, 60))}"
            seed = e_.seed if e_.seed is not None else ""
            s += f"| {journal.datetime(e_.t)} | `{e_.unit}` | {cell(result)} | `{seed}` |\n"
    return s


WEEK = 7 * 86_400


@dataclass(kw_only=True)
class Schedule:
    """Where the student stands against the planned hours of the required units."""

    # 1-based week of the course, counted from the first unlock.
    week: int
    weeks: float | None
    planned: float
    # Planned hours of the required units already passed.
    done: float
    # Planned hours the schedule expected by now.
    expected: float | None

    def status(self) -> str:
        """ "on track", "ahead by about 4 h" or "behind by about 9 h"."""
        expected = self.expected
        if expected is None:
            return "no schedule: the course has no `weeks`"
        gap = self.done - expected
        slack = max(self.planned * 0.05, 2.0)
        if abs(gap) < slack:
            return "on track"
        if gap > 0.0:
            return f"ahead by about {gap:.0f} h"
        return f"behind by about {-gap:.0f} h"

    def behind(self) -> bool:
        return self.status().startswith("behind")


def schedule(c: course.CourseDir, events: list[journal.Event], now: int) -> Schedule | None:
    state = c.state()
    required = [u for u in c.units if not u.stretch]
    planned = _fsum([u.hours for u in required if u.hours is not None])
    if planned <= 0.0:
        return None
    done = _fsum([u.hours for u in required if u.id in state.passed and u.hours is not None])
    if not events:
        return None
    start = min(e.t for e in events)
    elapsed = max(now - start, 0)
    w = c.course.weeks
    weeks = w if w is not None and w > 0.0 else None
    return Schedule(
        week=elapsed // WEEK + 1,
        weeks=weeks,
        planned=planned,
        done=done,
        expected=(
            planned * _fmin(float(elapsed) / (weeks * float(WEEK)), 1.0)
            if weeks is not None
            else None
        ),
    )


def _fmin(a: float, b: float) -> float:
    """Rust `f64::min`: a NaN loses to the other value."""
    if math.isnan(a):
        return b
    if math.isnan(b):
        return a
    return min(a, b)


def _round(x: float) -> float:
    """Rust `f64::round`: halves away from zero (Python's `round` goes to even)."""
    if not math.isfinite(x):
        return x
    r = math.copysign(float(math.trunc(x)), x)
    if abs(x - r) >= 0.5:
        r += math.copysign(1.0, x)
    return r


def _fract(x: float) -> float:
    """Rust `f64::fract`."""
    if not math.isfinite(x):
        return math.nan
    return x - math.copysign(float(math.trunc(x)), x)


def hours(h: float) -> str:
    """Hours to the nearest half: `8.5`, `8`."""
    h = _round(h * 2.0) / 2.0
    if _fract(h) == 0.0:
        return f"{h:.0f}"
    return f"{h:.1f}"


def schedule_md(sc: Schedule) -> str:
    s = "\n## Schedule\n\n| Metric | Value |\n|--------|-------|\n"
    week = f"{sc.week} of {float_display(sc.weeks)}" if sc.weeks is not None else str(sc.week)
    s += f"| Week | {week} |\n"
    s += f"| Planned work done | {hours(sc.done)} h of {hours(sc.planned)} h required ({sc.done * 100.0 / sc.planned:.0f}%) |\n"
    if sc.expected is not None:
        s += f"| Expected by now | {hours(sc.expected)} h |\n"
    s += f"| Status | {sc.status()} |\n"
    if sc.behind():
        s += "\nBehind plan is normal, progress is uneven. Put each project's minimum viable result first, skip stretch goals (`proctor skip`), and revisit the concept that slowed you down before pushing on.\n"
    return s


def weekly_review(c: course.CourseDir, now: int) -> str | None:
    """At the start of a new week, writes `reviews/week-NN.md` for the week that
    just ended (never overwriting). Returns its path relative to the course."""
    events = journal.read(c.root)
    if not events:
        return None
    start = min(e.t for e in events)
    week = max(now - start, 0) // WEEK + 1
    if week < 2:
        return None
    ended = week - 1
    rel = f"reviews/week-{ended:02}.md"
    path = c.root / rel
    if path.exists():
        return None
    from_, to = start + (ended - 1) * WEEK, start + ended * WEEK
    in_week = [e for e in events if from_ <= e.t < to]
    passed = [e.unit for e in in_week if e.ev == "pass"]
    checks = sum(1 for e in in_week if e.ev == "check")
    ok = sum(1 for e in in_week if e.ev == "check" and e.ok is True)
    sc = schedule(c, events, to)
    if sc is not None:
        if sc.expected is not None:
            sched = f"{sc.status()} ({sc.done:.0f} h of planned work done, {sc.expected:.0f} h expected)"
        else:
            sched = f"{sc.done:.0f} h of planned work done"
    else:
        sched = "no planned hours in this course"
    s = f"# Week {ended} review\n\nWritten by proctor when week {ended} ended. Fill it in: it is for you, nothing grades it.\n\n| Metric | Value |\n|--------|-------|\n"
    s += "| Units passed | {} |\n".format("none" if not passed else ", ".join(passed))
    s += f"| Checks run | {checks} ({ok} OK) |\n"
    s += f"| Schedule | {sched} |\n"
    s += (
        "\n## What can you now implement on your own, without looking anything up?\n\n\n"
        "## What is still unclear? Which concepts caused the most friction?\n\n\n"
        "## Is the schedule still realistic? What changes next week?\n\n"
        "Options: revisit a concept before moving on, skip a stretch goal (`proctor skip`), "
        "or plan more time. Each project's minimum viable result comes first.\n"
    )
    d = path.parent
    try:
        d.mkdir(parents=True, exist_ok=True)
    except OSError as e:
        raise Error(f"{d}: {io_error(e)}") from None
    try:
        write_text(path, s)
    except OSError as e:
        raise Error(f"{path}: {io_error(e)}") from None
    return rel


def write(c: course.CourseDir) -> None:
    events = journal.read(c.root)
    p = c.root / "PROGRESS.md"
    try:
        write_text(p, render(c, events))
    except OSError as e:
        raise Error(f"{p}: {io_error(e)}") from None
