//! PROGRESS.md, regenerated from the journal after every check. Never edited
//! by hand: the journal is the record, this is a view of it.

use crate::course::CourseDir;
use crate::journal::{self, Event, date, datetime, day_of, duration, week_start};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::fs;

/// Gaps longer than this between two checks are breaks, not work.
const SESSION_GAP: u64 = 45 * 60;

#[derive(Default)]
struct UnitStats {
    unlocked: Option<u64>,
    passed: Option<u64>,
    attempts: usize,
    attempts_to_pass: Option<usize>,
    active: u64,
    fails_by_cat: BTreeMap<String, usize>,
    fails_by_item: BTreeMap<String, usize>,
    last_fail_seed: Option<String>,
    warnings_at_pass: Option<usize>,
}

pub struct Stats {
    units: BTreeMap<String, UnitStats>,
    checks: Vec<Event>,
    active_by_day: BTreeMap<i64, u64>,
    first: Option<u64>,
    last: Option<u64>,
}

pub fn compute(events: &[Event]) -> Stats {
    let mut s = Stats {
        units: BTreeMap::new(),
        checks: Vec::new(),
        active_by_day: BTreeMap::new(),
        first: None,
        last: None,
    };
    let mut evs: Vec<&Event> = events.iter().collect();
    evs.sort_by_key(|e| e.t);
    let mut prev: Option<u64> = None;
    for e in evs {
        s.first.get_or_insert(e.t);
        s.last = Some(e.t);
        let u = s.units.entry(e.unit.clone()).or_default();
        match e.ev.as_str() {
            "unlock" => {
                u.unlocked.get_or_insert(e.t);
            }
            "pass" => {
                if u.passed.is_none() {
                    u.passed = Some(e.t);
                    u.attempts_to_pass = Some(u.attempts.max(1));
                }
            }
            "check" => {
                if let Some(p) = prev {
                    let gap = e.t.saturating_sub(p);
                    if gap <= SESSION_GAP {
                        u.active += gap;
                        *s.active_by_day.entry(day_of(e.t)).or_default() += gap;
                    }
                }
                u.attempts += 1;
                if e.ok == Some(true) {
                    if u.passed.is_none() {
                        u.warnings_at_pass = e.warnings;
                    }
                } else {
                    if let Some(cat) = &e.cat {
                        *u.fails_by_cat.entry(cat.clone()).or_default() += 1;
                    }
                    if let Some(item) = &e.item {
                        *u.fails_by_item.entry(item.clone()).or_default() += 1;
                    }
                    u.last_fail_seed = e.seed.clone();
                }
                s.checks.push(e.clone());
            }
            _ => {}
        }
        prev = Some(e.t);
    }
    s
}

fn pct(a: usize, b: usize) -> String {
    match (a * 100 + b / 2).checked_div(b) {
        Some(p) => format!("{p}%"),
        None => "n/a".into(),
    }
}

fn streak(active_days: &BTreeSet<i64>, today: i64) -> usize {
    let mut d = if active_days.contains(&today) {
        today
    } else {
        today - 1
    };
    let mut n = 0;
    while active_days.contains(&d) {
        n += 1;
        d -= 1;
    }
    n
}

pub fn render(c: &CourseDir, events: &[Event]) -> String {
    let st = compute(events);
    let state = c.state();
    let total_units = c.units.len();
    let passed: Vec<&str> = c
        .units
        .iter()
        .filter(|u| state.passed.contains(&u.id))
        .map(|u| u.id.as_str())
        .collect();
    let total_active: u64 = st.units.values().map(|u| u.active).sum();
    let checks = st.checks.len();
    let ok_checks = st.checks.iter().filter(|e| e.ok == Some(true)).count();
    let passed_stats: Vec<&UnitStats> = passed.iter().filter_map(|id| st.units.get(*id)).collect();
    let first_try = passed_stats
        .iter()
        .filter(|u| u.attempts_to_pass == Some(1))
        .count();
    let avg_attempts = if passed_stats.is_empty() {
        "n/a".to_string()
    } else {
        format!(
            "{:.1}",
            passed_stats
                .iter()
                .filter_map(|u| u.attempts_to_pass)
                .sum::<usize>() as f64
                / passed_stats.len() as f64
        )
    };
    let check_days: BTreeSet<i64> = st.checks.iter().map(|e| day_of(e.t)).collect();
    let today = day_of(journal::now());
    let weeks = match (st.first, st.last) {
        (Some(a), Some(b)) => ((b.saturating_sub(a)) as f64 / (7.0 * 86_400.0)).max(1.0 / 7.0),
        _ => 0.0,
    };

    let mut s = String::new();
    let _ = writeln!(s, "# Progress: {}\n", c.course.title);
    let _ = writeln!(
        s,
        "Generated by skillcheck from `.skillcheck/journal.jsonl` after every check. Do not edit by hand. Times are UTC.\n"
    );
    let _ = writeln!(s, "## Dashboard\n\n| Metric | Value |\n|--------|-------|");
    let _ = writeln!(
        s,
        "| Completion | {} / {} units ({}){} |",
        passed.len(),
        total_units,
        pct(passed.len(), total_units),
        match state.skipped.len() {
            0 => String::new(),
            n => format!(", {n} stretch goal(s) skipped"),
        }
    );
    let current_done = state.current.as_deref().is_some_and(|id| state.done(id));
    if current_done {
        let next = match state.next_locked(c) {
            Some(u) => format!("`{}` (run `skillcheck next` to unlock it)", u.id),
            None => "none: the course is complete".into(),
        };
        let _ = writeln!(s, "| Next | {next} |");
    } else if let Some(cur) = &state.current {
        let since = st
            .units
            .get(cur)
            .and_then(|u| u.unlocked)
            .map(date)
            .unwrap_or_default();
        let _ = writeln!(s, "| Current | `{cur}` (in progress, since {since}) |");
    }
    let _ = writeln!(
        s,
        "| Checks run | {checks} ({ok_checks} OK, {} KO) |",
        checks - ok_checks
    );
    let _ = writeln!(
        s,
        "| First-try passes | {first_try} / {} ({}) |",
        passed.len(),
        pct(first_try, passed.len())
    );
    let _ = writeln!(s, "| Average checks to pass | {avg_attempts} |");
    let _ = writeln!(s, "| Active time (estimate) | {} |", duration(total_active));
    let _ = writeln!(
        s,
        "| Active days | {} (current streak: {} day(s)) |",
        check_days.len(),
        streak(&check_days, today)
    );
    if let Some(f) = st.first {
        let _ = writeln!(s, "| Started | {} |", date(f));
    }
    if weeks > 0.0 {
        let hpw = total_active as f64 / 3600.0 / weeks;
        let target = c
            .course
            .hours_per_week
            .map(|t| format!(" (target {t} h)"))
            .unwrap_or_default();
        let _ = writeln!(
            s,
            "| Pace | {:.1} units / week, {:.1} h / week{target} |",
            passed.len() as f64 / weeks,
            hpw
        );
    }

    let _ = writeln!(
        s,
        "\n## Units\n\n| Unit | Difficulty | Status | Unlocked | Passed | Checks | First try | Active time | Most failed check |\n|------|-----------|--------|----------|--------|--------|-----------|-------------|-------------------|"
    );
    for u in &c.units {
        if !state.unlocked.contains(&u.id) {
            continue;
        }
        let us = st.units.get(&u.id);
        let status = if state.skipped.contains(&u.id) {
            "skipped (stretch)"
        } else if state.passed.contains(&u.id) {
            "passed"
        } else {
            "in progress"
        };
        let most = us
            .and_then(|x| x.fails_by_item.iter().max_by_key(|(_, n)| **n))
            .map(|(k, n)| format!("{} ({n}x)", k.replace('|', "\\|")))
            .unwrap_or_else(|| "none".into());
        let first_try = match us.and_then(|x| x.attempts_to_pass) {
            Some(1) => "yes",
            Some(_) => "no",
            None => "",
        };
        let _ = writeln!(
            s,
            "| `{}` | {} | {status} | {} | {} | {} | {first_try} | {} | {most} |",
            u.id,
            u.difficulty.map(|d| d.to_string()).unwrap_or_default(),
            us.and_then(|x| x.unlocked).map(date).unwrap_or_default(),
            us.and_then(|x| x.passed).map(date).unwrap_or_default(),
            us.map(|x| x.attempts).unwrap_or(0),
            us.map(|x| duration(x.active)).unwrap_or_default(),
        );
    }

    let mut by_cat: BTreeMap<String, usize> = BTreeMap::new();
    let mut by_item: BTreeMap<String, usize> = BTreeMap::new();
    for us in st.units.values() {
        for (k, n) in &us.fails_by_cat {
            *by_cat.entry(k.clone()).or_default() += n;
        }
        for (k, n) in &us.fails_by_item {
            *by_item.entry(k.clone()).or_default() += n;
        }
    }
    let fails: usize = by_cat.values().sum();
    if fails > 0 {
        let _ = writeln!(
            s,
            "\n## Where checks fail\n\nWhich step stopped a failing check. A high share points at a habit to work on.\n\n| Step | Failures | Share |\n|------|----------|-------|"
        );
        let mut cats: Vec<(&String, &usize)> = by_cat.iter().collect();
        cats.sort_by(|a, b| b.1.cmp(a.1));
        for (k, n) in cats {
            let _ = writeln!(s, "| {k} | {n} | {} |", pct(*n, fails));
        }
        let mut items: Vec<(&String, &usize)> = by_item.iter().collect();
        items.sort_by(|a, b| b.1.cmp(a.1));
        let _ = writeln!(
            s,
            "\nMost failed checks: {}.",
            items
                .iter()
                .take(5)
                .map(|(k, n)| format!("`{k}` ({n}x)"))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }

    let mut by_diff: BTreeMap<u8, (usize, usize, usize)> = BTreeMap::new();
    for u in &c.units {
        if let (Some(d), Some(us)) = (u.difficulty, st.units.get(&u.id))
            && let Some(a) = us.attempts_to_pass
        {
            let e = by_diff.entry(d).or_default();
            e.0 += 1;
            e.1 += a;
            e.2 += usize::from(a == 1);
        }
    }
    if !by_diff.is_empty() {
        let _ = writeln!(
            s,
            "\n## By difficulty\n\n| Difficulty | Units passed | Average checks to pass | First-try rate |\n|-----------|--------------|------------------------|----------------|"
        );
        for (d, (n, a, f)) in by_diff {
            let _ = writeln!(
                s,
                "| {d} / 5 | {n} | {:.1} | {} |",
                a as f64 / n as f64,
                pct(f, n)
            );
        }
    }

    let mut mastered: BTreeSet<String> = BTreeSet::new();
    let mut learning: BTreeSet<String> = BTreeSet::new();
    for u in &c.units {
        if state.passed.contains(&u.id) {
            mastered.extend(u.concepts.iter().cloned());
        } else if state.unlocked.contains(&u.id) {
            learning.extend(u.concepts.iter().cloned());
        }
    }
    learning.retain(|x| !mastered.contains(x));
    if !mastered.is_empty() || !learning.is_empty() {
        let _ = writeln!(s, "\n## Concepts\n");
        if !mastered.is_empty() {
            let _ = writeln!(
                s,
                "- Practised: {}",
                mastered.into_iter().collect::<Vec<_>>().join(", ")
            );
        }
        if !learning.is_empty() {
            let _ = writeln!(
                s,
                "- In progress: {}",
                learning.into_iter().collect::<Vec<_>>().join(", ")
            );
        }
    }

    let warn: Vec<(&str, usize)> = c
        .units
        .iter()
        .filter_map(|u| {
            st.units
                .get(&u.id)
                .and_then(|x| x.warnings_at_pass)
                .map(|w| (u.id.as_str(), w))
        })
        .collect();
    if warn.iter().any(|(_, w)| *w > 0) {
        let _ = writeln!(
            s,
            "\n## Build warnings at pass\n\n{}",
            warn.iter()
                .map(|(u, w)| format!("`{u}`: {w}"))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }

    let mut weeks_map: BTreeMap<i64, (usize, usize, u64)> = BTreeMap::new();
    for e in &st.checks {
        let w = weeks_map.entry(week_start(e.t)).or_default();
        w.0 += 1;
        w.1 += usize::from(e.ok == Some(true));
    }
    for (day, secs) in &st.active_by_day {
        let wk = day - (day + 3).rem_euclid(7);
        weeks_map.entry(wk).or_default().2 += secs;
    }
    if !weeks_map.is_empty() {
        let _ = writeln!(
            s,
            "\n## Weekly activity\n\n| Week of | Checks | OK | Active time |\n|---------|--------|----|-------------|"
        );
        for (wk, (n, ok, secs)) in weeks_map.iter().rev().take(12) {
            let _ = writeln!(
                s,
                "| {} | {n} | {ok} | {} |",
                date(*wk as u64 * 86_400),
                duration(*secs)
            );
        }
    }

    if !st.checks.is_empty() {
        let _ = writeln!(
            s,
            "\n## Recent checks\n\n| When | Unit | Result | Seed |\n|------|------|--------|------|"
        );
        for e in st.checks.iter().rev().take(10) {
            let result = if e.ok == Some(true) {
                format!("OK {}/{}", e.passed.unwrap_or(0), e.total.unwrap_or(0))
            } else {
                let what = e.item.clone().unwrap_or_default();
                format!("KO {}: {}", e.cat.clone().unwrap_or_default(), what).replace('|', "\\|")
            };
            let _ = writeln!(
                s,
                "| {} | `{}` | {} | `{}` |",
                datetime(e.t),
                e.unit,
                crate::report::truncate(&result, 70),
                e.seed.clone().unwrap_or_default()
            );
        }
    }
    s
}

pub fn write(c: &CourseDir) -> Result<(), String> {
    let events = journal::read(&c.root);
    let p = c.root.join("PROGRESS.md");
    fs::write(&p, render(c, &events)).map_err(|e| format!("{}: {e}", p.display()))
}
